export function t(key: string, replacements?: Record<string, string | number>): string {
  let value = strings[key] ?? key;
  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      value = value.replace(`{${k}}`, String(v));
    });
  }
  return value;
}
